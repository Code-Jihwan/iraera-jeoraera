// 운영 전에 사람이 한 번 검수해야 하고, 은어는 빨리 바뀌므로 주기적으로 손봐야 한다.
// 게이·무슬림·장애인·조선족 같은 정체성 낱말은 일부러 넣지 않았다(그 말을 막는 것이 곧 차별이다).
// 실존 인물 이름은 목록으로 따라갈 수 없어 여기서 다루지 않는다 — 생성 단계의 AI 심사와 사람 검수가 맡는다.
//
// 항목: { term, category, severity, boundary?, noun?, spaced?, allow? }
//   category  shared/constants.js SAFETY_CATEGORIES의 키
//   severity  'block' 항상 막는다 / 'caution' 통과시키되 표시한다
//             (tragedy·self_harm·other의 caution은 트렌드 단계에서는 막는다 — filter.js)
//   boundary  true면 낱말 첫머리(띄어쓰기·문장부호·자모 바로 뒤)에서만 맞춘다. 두 글자 이하와 띄어 쓴 구는
//             적지 않아도 true, 어디에 붙어도 뜻이 하나뿐인 짧은 말만 false로 풀어 준다.
//   noun      true면 낱말 첫머리에서 명사로 읽힐 때만 맞춘다(‘보지 마’, ‘안 자지?’처럼 흔한 활용형과 겹치는 말 — filter.js).
//   spaced    true면 욕설이 아니어도 두 글자 말의 띄어 쓴 변형(‘섹 스’)까지 잡는다.
//   allow     이 말을 품고 있지만 문제없는 낱말. 띄어 쓴 자리에서만 띄어쓰기를 넘어 맞춘다.
// 띄어 쓴 항목(‘극단적 선택’)은 구로 보고 띄어쓰기와 상관없이 맞춘다. 붙여 쓴 항목은 욕설, 세 글자 이상인 말, spaced 항목만
// 띄어 쓴 변형(‘시 발’, ‘세 월 호’)까지 잡되, 낱말 경계에서 시작해 낱말 경계에서 끝날 때만 본다(‘다시 발표’, ‘씨 발아’는 걸리지 않는다).
// 영문·숫자만으로 된 말은 소문자로 적는다. 낱말 첫머리에서 낱말 끝까지 맞을 때만 잡고, 띄어 쓰거나 점을 찍거나
// 글자를 늘인 꼴(f u c k, s.e.x, fuuuck)도 잡는다. 한글·기호가 섞인 말(18놈, f*ck)은 원문에서 그 꼴 그대로만 찾는다.

